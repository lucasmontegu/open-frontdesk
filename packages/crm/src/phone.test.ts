import { describe, expect, it } from "vitest";
import { normalizeArgentinePhone as n } from "./phone.js";

describe("normalizeArgentinePhone", () => {
  it.each([
    ["+54 9 11 1234-5678", "+5491112345678"],
    ["+5491112345678", "+5491112345678"],
    ["5491112345678", "+5491112345678"],
    ["+54 11 1234 5678", "+5491112345678"],
    ["011 1234-5678", "+5491112345678"],
    ["011 15 1234-5678", "+5491112345678"],
    ["(011) 15-1234-5678", "+5491112345678"],
    ["11 1234 5678", "+5491112345678"],
    ["15 1234 5678 con area 11", null],
    ["1112345678", "+5491112345678"],
    ["0351 15 456 7890", "+5493514567890"],
    ["0351 456-7890", "+5493514567890"],
    ["0341 15 4123456", "+5493414123456"],
    ["02214 15 123456", "+5492214123456"],
    ["+54 9 351 456 7890", "+5493514567890"],
    ["0054 9 11 1234 5678", "+5491112345678"],
    ["+54 0 11 1234 5678", "+5491112345678"],
    ["+34 612 345 678", "+34612345678"],
    ["+1 (415) 555-2671", "+14155552671"],
  ])("%s -> %s", (input, expected) => {
    expect(n(input)).toBe(expected);
  });

  it("rejects garbage", () => {
    expect(n("")).toBeNull();
    expect(n("abc")).toBeNull();
    expect(n("1234")).toBeNull();
    expect(n("+54 11 123")).toBeNull();
  });
});
